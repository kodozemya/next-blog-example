"use client";

/**
 * Що показати, коли на сторінці впала помилка.
 *
 * Це не 404 — 404 живе в not-found.tsx. Тут інше: код кинув виключення,
 * якого ніхто не чекав (наприклад, у статті поламаний фронтматер).
 * Без цього файла користувач побачив би порожній екран, а в продакшні —
 * стандартну сторінку Next.js без жодної підказки.
 *
 * "use client" тут обов'язковий, і не через стан: error.tsx мусить
 * працювати в браузері, бо ловить і ті помилки, що трапилися вже після
 * завантаження сторінки. Це межа помилок (error boundary), а вони
 * в React бувають лише клієнтськими.
 */
export default function Error({ reset }: { error: Error; reset: () => void }) {
  return (
    <section className="section">
      <div className="container not-found">
        <h1 className="section__title">Щось пішло не так</h1>
        <p className="not-found__text">
          Сторінку не вдалося показати. Спробуй ще раз — можливо, це разова
          помилка.
        </p>
        {/*
          reset() дає React команду перемалювати цю ділянку заново.
          Текст помилки користувачу не показуємо: у ньому бувають шляхи
          на диску й інші подробиці, яких стороннім бачити не варто.
          Next.js сам пише їх у логи сервера.
        */}
        <button className="button" type="button" onClick={reset}>
          Спробувати ще раз
        </button>
      </div>
    </section>
  );
}
