import { NextResponse } from "next/server";

import { getAllPosts } from "@/lib/posts";

/**
 * GET /api/posts — список статей у JSON.
 *
 * Той самий getAllPosts(), що живить сторінки. Одна функція — один порядок
 * сортування і однакові дані скрізь; дві функції рано чи пізно розійдуться.
 *
 * Сторінки цей роут не викликають: вони серверні й читають статті напряму,
 * без зайвого кола через мережу. Роут існує для тих, хто ззовні: скрипт,
 * що збирає стрічку, стороння сторінка, звичайний curl під час перевірки.
 *
 * Ім'я експорту — це метод HTTP. Щоб з'явився POST, дописують
 * `export async function POST(...)` у цьому ж файлі; на решту методів
 * Next.js сам відповість 405.
 */
export async function GET() {
  try {
    const posts = await getAllPosts();

    /*
      Тіло статей сюди не потрапляє — лише фронтматер. Роут існує для
      пошуку й списків, а віддавати текст усіх статей одним запитом
      означало б качати мегабайти заради одного заголовка.
    */
    return NextResponse.json(posts);
  } catch (error: unknown) {
    /*
      Помилка сервера не має витікати назовні текстом: у ній буває
      шлях на диску й інші подробиці. Клієнту — статус і коротке
      повідомлення, подробиці — у логи сервера.

      Саме тому тут стоїть console.error: без нього подробиці не потрапили б
      нікуди взагалі, і причину падіння шукали б навмання. На Vercel цей
      вивід видно у вкладці Logs.
    */
    console.error("GET /api/posts не вдався:", error);

    return NextResponse.json({ error: "Не вдалося прочитати статті" }, { status: 500 });
  }
}
