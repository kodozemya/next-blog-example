/**
 * Форматування дати статті.
 *
 * Лежить у lib/, а не всередині компонента: цю функцію викликають і картка,
 * і сторінка статті. Утиліта, яку імпортують із двох місць, — уже не
 * частина компонента, і тягнути її звідти означало б тягнути разом
 * із нею весь компонент.
 */

/**
 * «2026-08-13» → «13 серпня 2026».
 *
 * Intl робить це сам, з правильними відмінками для української.
 * Власний масив назв місяців дав би «13 серпень 2026».
 *
 * timeZone: "UTC" тут обов'язковий. `new Date("2026-08-13")` — це північ
 * за UTC, і без цього рядка Intl показав би дату в поясі того, хто
 * форматує: сервер у Києві сказав би «13 серпня», а браузер у Нью-Йорку —
 * «12 серпня». Дата статті не залежить від того, звідки її читають.
 */
export function formatDate(isoDate: string): string {
  return new Intl.DateTimeFormat("uk-UA", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(isoDate));
}
